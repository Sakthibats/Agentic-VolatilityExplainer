# ── Markdown → HTML ──────────────────────────────────────────────────────────

def _md_to_html(text: str) -> str:
    lines = text.split("\n")
    out: list[str] = []
    in_list: str | None = None

    def close_list() -> None:
        nonlocal in_list
        if in_list:
            out.append(f"</{in_list}>")
            in_list = None

    def fmt(s: str) -> str:
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"_([^_\n]+)_", r"<em>\1</em>", s)
        s = re.sub(r"(?<!\*)\*([^*\n]+)\*(?!\*)", r"<em>\1</em>", s)
        return s

    for line in lines:
        stripped = line.strip()
        if not stripped:
            close_list()
            continue
        # Escape BEFORE any markdown-marker parsing below — this text is LLM-authored
        # (ultimately sourced from external news headlines an attacker could influence),
        # so any literal <, >, & must become inert entities before we ever interpolate it
        # into HTML. html.escape() doesn't touch *, _, #, -, digits, so the markdown
        # detection/formatting below (which only cares about those characters) still works
        # on the escaped text; fmt() then only ever adds tags we control ourselves.
        stripped = html.escape(stripped)

        m = re.match(r"^(\d+)\.\s+(.+)$", stripped)
        if m:
            if in_list == "ul":
                close_list()
            if not in_list:
                out.append('<ol class="analysis-list" style="margin:0.5rem 0 0.75rem 1.4rem;padding:0;">')
                in_list = "ol"
            # Explicit value= — the evidence/caveat lines below each hypothesis title aren't
            # list items themselves, so they close this <ol> right after one <li>. Without
            # value=, a lone <li> always displays "1." regardless of the source number.
            out.append(f'<li value="{m.group(1)}" style="margin-bottom:0.5rem;font-size:0.88rem;line-height:1.7;color:#0F172A;">{fmt(m.group(2))}</li>')
            continue

        m2 = re.match(r"^[-•]\s+(.+)$", stripped)
        if m2:
            if in_list == "ol":
                close_list()
            if not in_list:
                out.append('<ul class="analysis-list" style="margin:0.5rem 0 0.75rem 1.4rem;padding:0;">')
                in_list = "ul"
            out.append(f'<li style="margin-bottom:0.5rem;font-size:0.88rem;line-height:1.7;color:#0F172A;">{fmt(m2.group(1))}</li>')
            continue

        close_list()

        m3 = re.match(r"^(#{1,4})\s+(.+)$", stripped)
        if m3:
            out.append(
                f'<p style="font-weight:700;font-size:0.95rem;color:#0F172A;'
                f'margin:0.9rem 0 0.3rem;letter-spacing:-0.015em;">{fmt(m3.group(2))}</p>'
            )
            continue

        out.append(
            f'<p style="font-size:0.88rem;line-height:1.8;color:#334155;margin:0 0 0.6rem 0;">{fmt(stripped)}</p>'
        )

    close_list()
    return "\n".join(out)


