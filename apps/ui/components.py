def render_brand_header() -> None:
    """Brand block, Beta tag, and the Home/About nav — one row, same header bar.

    Deliberately st.button, not a real `<a href="?view=...">` — an anchor tag navigates
    the browser (full document reload, session re-init flash) even for a same-page query
    string change. A widget click only triggers Streamlit's normal script-rerun-over-the-
    existing-WebSocket path, which never reloads the page. The buttons are reset with
    `all: unset` in theme.py and re-skinned as a pill nav so they don't look like buttons."""
    view = st.session_state.get("view", "main")
    with st.container(key="app_header_row"):
        col_brand, col_tag, col_nav = st.columns(
            [8, 1, 1.5], gap="small", vertical_alignment="center"
        )
        with col_brand:
            st.markdown(
                '<div class="header-brand">'
                '<div class="header-logo">AME</div>'
                '<div>'
                '<span class="header-title">Agentic Market Explainer</span>'
                '<span class="header-sub">AI investigates why any stock or market moved — multi-agent analysis</span>'
                '</div>'
                '</div>',
                unsafe_allow_html=True,
            )
        with col_tag:
            st.markdown(
                '<div class="header-tag-wrap"><span class="header-tag">Beta</span></div>',
                unsafe_allow_html=True,
            )
        with col_nav:
            # Nested container gives the pair a shared pill "track" background (the
            # segmented-control look) — two bare st.button widgets side by side have no
            # single element to hang that background/border on.
            with st.container(key="nav_group"):
                col_home, col_about = st.columns([1, 1], gap="small")
                with col_home:
                    st.button(
                        "Home",
                        key="nav_home",
                        type="primary" if view == "main" else "secondary",
                        on_click=_go_home,
                    )
                with col_about:
                    st.button(
                        "About",
                        key="nav_about",
                        type="primary" if view == "about" else "secondary",
                        on_click=_go_about,
                    )


def _start_analysis() -> None:
    query = st.session_state.get("search_input", "").strip()
    if query:
        st.session_state["submitted_query"] = query
        st.session_state["analysis_phase"] = "running"
        st.session_state["visible_tiles"] = 0
        st.session_state["analysis_result"] = None
        st.session_state["all_tiles"] = []


def _stop_analysis() -> None:
    st.session_state["analysis_phase"] = "stopped"


def render_search_bar() -> str:
    # Callbacks (on_click) run *before* the script reruns, so session_state
    # already reflects the click by the time the button label below is
    # computed — a plain `if submitted:` check after the fact would only
    # update the label on the following rerun (i.e. the next click).
    is_running = st.session_state.get("analysis_phase") == "running"

    # st.form gives us a real DOM container we can style as a card via CSS.
    # A custom <div> wrapper around st.columns() doesn't work — Streamlit
    # renders its own column containers outside any preceding markdown div.
    with st.form(key="search_form", clear_on_submit=False, border=False):
        col_input, col_btn = st.columns([8, 1], gap="small", vertical_alignment="center")
        with col_input:
            query = st.text_input(
                "Search",
                placeholder="Try: TSLA · why did Tesla dip? · what happened to gold? · market down?",
                label_visibility="collapsed",
                key="search_input",
                disabled=is_running,
                autocomplete="off",
            )
        with col_btn:
            if is_running:
                st.form_submit_button(
                    "Stop",
                    type="primary",
                    width="stretch",
                    on_click=_stop_analysis,
                )
            else:
                st.form_submit_button(
                    "Analyze →",
                    type="primary",
                    width="stretch",
                    on_click=_start_analysis,
                )

    return query


